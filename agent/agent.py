"""End-to-end Research Agent orchestrator — Member B (AI reasoning & orchestration).

Coordinates query planning, literature retrieval, multi-criteria paper scoring,
and evidence-grounded research synthesis into a unified research report.
"""

from __future__ import annotations

import logging
from collections.abc import Callable

from pydantic import BaseModel, Field, field_validator

from agent.overview import OverviewEngine, ResearchOverview
from agent.planner import QueryPlan, QueryPlanner
from agent.scoring import score_papers
from shared.models import Paper

logger = logging.getLogger(__name__)


def _default_search(
    query: str,
    limit: int = 10,
    offset: int = 0,
    providers: list[str] | None = None,
    enrich_access: bool = False,
    use_cache: bool = True,
) -> list[Paper]:
    """Execute search via data.search.search."""
    import importlib

    mod = importlib.import_module("data.search")
    search_fn: Callable[..., list[Paper]] = mod.search
    return search_fn(
        query=query,
        limit=limit,
        offset=offset,
        providers=providers,
        enrich_access=enrich_access,
        use_cache=use_cache,
    )


def _deduplicate_papers(papers: list[Paper]) -> list[Paper]:
    """Deduplicate papers via data.search.deduplicate_papers."""
    import importlib

    mod = importlib.import_module("data.search")
    dedup_fn: Callable[[list[Paper]], list[Paper]] = mod.deduplicate_papers
    return dedup_fn(papers)


class ResearchAgentError(Exception):
    """Base exception for research agent orchestration failures."""


class RetrievalDiagnostic(BaseModel):
    """Execution status and paper count for a single planned query."""

    query: str = Field(..., description="The planned query string executed.")
    status: str = Field(
        ...,
        description="Query outcome: 'success' (papers found), 'empty' (0 papers returned), or 'failed' (exception raised).",
    )
    paper_count: int = Field(default=0, ge=0, description="Raw papers retrieved by this query.")
    error_message: str | None = Field(default=None, description="Error detail if retrieval raised an exception.")


class ResearchAgentResult(BaseModel):
    """Structured end-to-end research synthesis report."""

    topic: str = Field(..., description="The original research topic or goal.")
    plan: QueryPlan = Field(..., description="The academic query plan generated by QueryPlanner.")
    total_retrieved: int = Field(
        ge=0,
        description="Total raw papers retrieved across all queries before deduplication.",
    )
    total_deduplicated: int = Field(
        ge=0,
        description="Unique candidate papers after cross-query deduplication.",
    )
    ranked_papers: list[Paper] = Field(
        default_factory=list,
        description="Candidate papers scored and sorted in descending order of quality.",
    )
    overview: ResearchOverview = Field(
        ...,
        description="Thematic clusters, executive verdict, and calibrated confidence synthesized by OverviewEngine.",
    )
    diagnostics: list[RetrievalDiagnostic] = Field(
        default_factory=list,
        description="Per-query retrieval execution status and diagnostics.",
    )

    @field_validator("topic")
    @classmethod
    def validate_topic(cls, v: str) -> str:
        cleaned = v.strip() if isinstance(v, str) else ""
        if not cleaned:
            raise ValueError("Topic must be a non-empty string.")
        return cleaned


class ResearchAgent:
    """Orchestrator driving query planning, literature retrieval, scoring, and overview synthesis."""

    def __init__(
        self,
        planner: QueryPlanner | None = None,
        overview_engine: OverviewEngine | None = None,
        search_fn: Callable[..., list[Paper]] | None = None,
        provider: str | None = None,
        api_key: str | None = None,
        model: str | None = None,
    ) -> None:
        self.search_fn = search_fn or _default_search

        # Configure or inject QueryPlanner
        if planner is not None:
            self.planner = planner
        else:
            self.planner = QueryPlanner(
                provider=provider,
                api_key=api_key,
                model=model,
            )

        # Configure or inject OverviewEngine
        if overview_engine is not None:
            self.overview_engine = overview_engine
        else:
            self.overview_engine = OverviewEngine(
                provider=provider,
                api_key=api_key,
                model=model,
            )

    def run(
        self,
        topic: str,
        per_query_limit: int = 10,
        max_overview_papers: int | None = 20,
        weights: dict[str, float] | None = None,
        threshold: float = 0.70,
        enrich_access: bool = False,
        use_cache: bool = True,
    ) -> ResearchAgentResult:
        """Execute end-to-end research synthesis on a topic.

        Parameters
        ----------
        topic : str
            The user-supplied research topic, query, or question. Must be a non-empty string.
        per_query_limit : int, default 10
            Maximum number of papers to retrieve per individual planned query.
        max_overview_papers : int | None, default 20
            Maximum top-scored papers to supply as candidate evidence to OverviewEngine.
            Pass None to supply all scored papers.
        weights : dict[str, float] | None
            Custom scoring weights for score_papers.
        threshold : float, default 0.70
            Recommendation threshold for paper scoring.
        enrich_access : bool, default False
            Whether retrieval should enrich results with Unpaywall open-access metadata.
        use_cache : bool, default True
            Whether retrieval should check local query cache.

        Returns
        -------
        ResearchAgentResult
            Structured result containing query plan, retrieval stats, ranked papers,
            and the evidence-grounded overview and verdict.

        Raises
        ------
        ValueError
            If topic is empty, whitespace-only, or not a string.
        ResearchAgentError
            If query planning or overview synthesis fails.
        """
        if not isinstance(topic, str) or not topic.strip():
            raise ValueError("Topic must be a non-empty string.")

        clean_topic = topic.strip()

        # Step 1: Query Planning
        try:
            plan = self.planner.plan(clean_topic)
        except Exception as exc:
            raise ResearchAgentError(f"Query planning failed for topic '{clean_topic}': {exc}") from exc

        # Step 2: Multi-Query Retrieval
        raw_papers: list[Paper] = []
        diagnostics: list[RetrievalDiagnostic] = []

        for item in plan.queries:
            q_str = item.query
            try:
                q_papers = self.search_fn(
                    query=q_str,
                    limit=per_query_limit,
                    enrich_access=enrich_access,
                    use_cache=use_cache,
                )
                if not isinstance(q_papers, list):
                    q_papers = []

                p_count = len(q_papers)
                raw_papers.extend(q_papers)
                # Note: an empty result does not prove providers were healthy or unhealthy;
                # it strictly records that 0 papers were returned for this query string.
                status = "success" if p_count > 0 else "empty"
                diagnostics.append(
                    RetrievalDiagnostic(
                        query=q_str,
                        status=status,
                        paper_count=p_count,
                    )
                )
            except Exception as exc:  # noqa: BLE001 - resilience to arbitrary provider or network failure
                logger.warning("Retrieval call failed for query '%s': %s", q_str, exc)
                diagnostics.append(
                    RetrievalDiagnostic(
                        query=q_str,
                        status="failed",
                        paper_count=0,
                        error_message=str(exc),
                    )
                )

        total_retrieved = len(raw_papers)

        # Step 3: Deduplication across all queries
        deduped_papers = _deduplicate_papers(raw_papers)
        total_deduped = len(deduped_papers)

        # Step 4: Multi-Criteria Scoring & Ranking
        try:
            ranked_papers = score_papers(
                deduped_papers,
                weights=weights,
                threshold=threshold,
            )
        except Exception as exc:
            raise ResearchAgentError(f"Paper scoring failed for topic '{clean_topic}': {exc}") from exc

        # Step 5: Select candidate evidence subset for overview synthesis
        candidate_papers = (
            ranked_papers[:max_overview_papers]
            if max_overview_papers is not None and max_overview_papers > 0
            else ranked_papers
        )

        # Step 6: Evidence-Grounded Overview & Verdict Synthesis
        try:
            overview = self.overview_engine.generate_overview(
                papers=candidate_papers,
                topic=clean_topic,
            )
        except Exception as exc:
            raise ResearchAgentError(f"Overview synthesis failed for topic '{clean_topic}': {exc}") from exc

        # Step 7: Return structured result
        return ResearchAgentResult(
            topic=clean_topic,
            plan=plan,
            total_retrieved=total_retrieved,
            total_deduplicated=total_deduped,
            ranked_papers=ranked_papers,
            overview=overview,
            diagnostics=diagnostics,
        )
